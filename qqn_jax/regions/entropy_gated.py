"""Entropy-gated per-sample trust regions (EG-PTGP).

Implements ``docs/entropy_gated_regions.md``. A training sample is either
an *objective* (misclassified, or correct-but-uncertain) or a *constraint*
(correct **and** low-entropy, i.e. "memorized"). The gate is
information-theoretic and two-sided::

    s_i = c_i · sigmoid(−β (H_i − H_mem))          (stability weight)
    α_i = 1 − s_i                                  (objective weight)

Two channels fall out of the gate:

* **Objective channel** (:func:`make_gated_loss`): the α-weighted
  cross-entropy — an *entropy hinge* that stops pushing a sample once its
  entropy falls below ``H_mem``.
* **Constraint channel** (:func:`EntropyGatedRegion`): the proposed step
  ``step = candidate − x`` is projected onto the polyhedral no-decrease
  cone generated by the memorized samples' margin gradients ``v_i``::

      s* = argmin ½‖s − step‖²   s.t.  ⟨−v̄_c, s⟩ ≤ ε̄_c   ∀ regions c

  solved through the NNLS dual (Appendix B). Only samples *about to be
  damaged by the aggregate step* pay a non-zero multiplier λ_c (the
  "price of stability", §4.4). Constraints are organised by a **region
  policy** (§3.7): one region (A-GEM-style mean), one per class, one per
  (class, runner-up) decision boundary, gradient-space clusters, random
  partition (control), or one per sample (exact cone).

The region operates on flat parameter vectors (it raveles pytrees at the
boundary) so it composes with every QQN oracle and line search. All
control flow is static-shape (``jnp.where`` / ``lax.fori_loop`` /
``lax.cond``) so the region is ``jit`` / ``vmap`` safe; the number of
constraints is bounded by ``max_constraints`` to keep shapes static. The
two genuinely expensive branches — the whole constraint channel during
warmup and the centroid refresh of the ``gradient`` policy — are skipped
with ``lax.cond`` rather than computed-and-discarded.
"""

from __future__ import annotations

from typing import Any, Callable, NamedTuple, Optional

import jax
import jax.numpy as jnp
import numpy as np
from jax.flatten_util import ravel_pytree

from qqn_jax.regions.types import Region

